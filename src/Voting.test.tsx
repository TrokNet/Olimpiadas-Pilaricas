// @vitest-environment happy-dom
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import Voting from './Voting';
import raw from './data/tournament.json';
import type { Tournament } from './types';
afterEach(() => { cleanup(); vi.unstubAllGlobals(); localStorage.clear(); });
it('limits the draft to three teams and announces success only after the server saves', async () => {
  const data = raw as Tournament;
  const ranking = data.grades.map((g) => ({ team_id: g.id, votes: 0 }));
  const fetchMock = vi.fn(async (_url: unknown, options?: RequestInit) => {
    const ids = options?.method === 'PUT' ? JSON.parse(String(options.body)).team_ids : [];
    return new Response(JSON.stringify({ ranking, my_votes: ids, voters: ids.length ? 1 : 0 }), { status: 200 });
  });
  vi.stubGlobal('fetch', fetchMock);
  render(<Voting data={data} />);
  await waitFor(() => expect(fetchMock).toHaveBeenCalled());
  fireEvent.click(screen.getByRole('button', { name: /Votar y ver ranking/ }));
  const boxes = await screen.findAllByRole('checkbox');
  fireEvent.click(boxes[0]);fireEvent.click(boxes[1]);fireEvent.click(boxes[2]);fireEvent.click(boxes[3]);
  expect(screen.getByText('3 de 3 equipos')).toBeTruthy();
  expect((boxes[3] as HTMLInputElement).checked).toBe(false);
  fireEvent.click(screen.getByRole('button', { name: /Confirmar mis votos/ }));
  await screen.findByText(/Tus votos están guardados/);
  const write = fetchMock.mock.calls.find((call) => call[1]?.method === 'PUT');
  expect(JSON.parse(String(write?.[1]?.body)).team_ids).toHaveLength(3);
  fireEvent.click(screen.getByRole('button', { name: 'Cerrar' }));
  fireEvent.click(await screen.findByRole('button', { name: 'Pausar movimiento de votaciones' }));
  expect(screen.getByRole('button', { name: 'Reanudar movimiento de votaciones' }).getAttribute('aria-pressed')).toBe('true');
});
it('searches by team or grade, removes selected chips and shows no medals for zero votes', async () => {
  const data = raw as Tournament;
  vi.stubGlobal('fetch', vi.fn(async () => new Response(JSON.stringify({ ranking: data.grades.map((g) => ({ team_id: g.id, votes: 0 })), my_votes: [], voters: 0 }))));
  render(<Voting data={data} />);
  fireEvent.click(await screen.findByRole('button', { name: 'Ver votos de Mailhac' }));
  await screen.findByText('Sin votos todavía');
  expect(document.querySelectorAll('.voting-ranking .place-1')).toHaveLength(0);
  const search = screen.getByRole('searchbox', { name: 'Buscar equipo o grado para votar' });
  expect((search as HTMLInputElement).value).toBe('Mailhac');
  expect(screen.getAllByRole('checkbox')).toHaveLength(1);
  fireEvent.click(screen.getByRole('checkbox', { name: 'Votar por Mailhac' }));
  expect(screen.getByText('1 de 3 equipos')).toBeTruthy();
  fireEvent.change(search, { target: { value: 'Cuarto Primaria' } });
  expect(screen.getAllByRole('checkbox')).toHaveLength(1);
  expect(screen.getByRole('checkbox', { name: 'Votar por Fonte Colombo' })).toBeTruthy();
  fireEvent.click(screen.getByRole('button', { name: 'Quitar voto a Mailhac' }));
  expect(screen.getByText('0 de 3 equipos')).toBeTruthy();
  fireEvent.change(search, { target: { value: 'equipo inexistente' } });
  expect(screen.queryAllByRole('checkbox')).toHaveLength(0);
  expect(screen.getByText(/No encontramos ese equipo/)).toBeTruthy();
});
